//WRITE A PROGRAM to Accept the Values of Two Variables
#include <stdio.h>

int main()
{
    int a, b;

    printf("Enter the value of first variable: ");
    scanf("%d", &a);

    printf("Enter the value of second variable: ");
    scanf("%d", &b);

    printf("Value of first variable = %d\n", a);
    printf("Value of second variable = %d", b);

    return 0;
}